/**
 * Traverses visible text nodes in the DOM and replaces them with translations
 */
function applySiteLanguage(langKey, savePreference = true) {
  if (!SITE_TRANSLATIONS[langKey]) langKey = 'en';

  if (savePreference) {
    try {
      localStorage.setItem('site_preferred_lang', langKey);
    } catch (e) {}
  }

  // 1. Toggle RTL / LTR layout
  const isRtl = langKey === 'ar';
  document.documentElement.setAttribute('dir', isRtl ? 'rtl' : 'ltr');
  document.documentElement.setAttribute('lang', langKey);

  // 2. Update navbar language code display
  const currentCodeEl = document.getElementById('langCurrentCode');
  if (currentCodeEl) {
    currentCodeEl.textContent = langKey.toUpperCase();
  }

  // 3. Highlight selected language option
  const langOptions = document.querySelectorAll('.lang-option-item');
  langOptions.forEach(opt => {
    const isSelected = opt.getAttribute('data-lang') === langKey;
    opt.classList.toggle('active', isSelected);
    opt.setAttribute('aria-selected', isSelected ? 'true' : 'false');
  });

  const dict = SITE_TRANSLATIONS[langKey] || SITE_TRANSLATIONS['en'];
  const isEn = langKey === 'en';

  // 4. Recursive TreeWalker for all visible text nodes
  const walker = document.createTreeWalker(
    document.body,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode: function(node) {
        const parent = node.parentElement;
        if (!parent) return NodeFilter.FILTER_REJECT;
        const tag = parent.tagName.toLowerCase();
        if (tag === 'script' || tag === 'style' || tag === 'noscript' || tag === 'textarea') {
          return NodeFilter.FILTER_REJECT;
        }
        // Avoid touching the language dropdown itself
        if (parent.closest('#langDropdownMenu') || parent.closest('#langToggleBtn')) {
          return NodeFilter.FILTER_REJECT;
        }
        const val = node.nodeValue.trim();
        if (!val) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    }
  );

  const textNodes = [];
  while (walker.nextNode()) {
    textNodes.push(walker.currentNode);
  }

  textNodes.forEach(node => {
    const parent = node.parentElement;
    if (!parent) return;

    // Cache original English text on the text node itself to avoid sibling text node collisions
    if (typeof node._i18nOrig === 'undefined') {
      node._i18nOrig = node.nodeValue;
    }

    if (isEn) {
      if (node.nodeValue !== node._i18nOrig) {
        node.nodeValue = node._i18nOrig;
      }
      return;
    }

    const origTrim = node._i18nOrig.trim();
    if (!origTrim) return;

    // Try direct exact match
    const cleanOrig = origTrim.replace(/\s+/g, ' ');
    if (dict[cleanOrig]) {
      node.nodeValue = node.nodeValue.replace(origTrim, dict[cleanOrig]);
      return;
    }

    // Try case-insensitive lookup
    const lowerOrig = cleanOrig.toLowerCase();
    for (const [k, v] of Object.entries(dict)) {
      if (k.toLowerCase() === lowerOrig) {
        node.nodeValue = node.nodeValue.replace(origTrim, v);
        return;
      }
    }
  });

  // 5. Explicit data-i18n attributes
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (!el.hasAttribute('data-i18n-orig')) {
        el.setAttribute('data-i18n-orig', el.textContent.trim());
      }
      el.textContent = dict[key];
    }
  });

  // 6. Dispatch event for custom components
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: langKey } }));
}

// Global exports
window.applySiteLanguage = applySiteLanguage;
window.SITE_TRANSLATIONS = SITE_TRANSLATIONS;
